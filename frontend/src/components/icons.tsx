import SvgIcon, { type SvgIconProps } from './SvgIcon';

/**
 * Interface icons — [Heroicons](https://heroicons.com) 24px solid.
 *
 * Every icon is an `SvgIcon`, so it keeps the MUI contract (`sx`, `fontSize`,
 * `color`, `aria-hidden`, currentColor) and can be dropped anywhere a
 * `@mui/icons-material` component was used.
 *
 * Two flavours ship here:
 *
 *  - `Solid` — filled shapes, the default look of the set;
 *  - `Stroke` — the 1.5px outline variants, used by the navigation items
 *    (home / queue / library / settings); their paths carry `strokeProps`
 *    instead of a fill.
 *
 * Heroicons ships no shuffle, repeat, volume or "explicit" glyphs, so those
 * keep their Material equivalents — same for sort, edit and playlist-add,
 * and the heart / chevron helpers.  It ships no logos either — the three
 * brand marks at the bottom come from Material Design Icons
 * ([Pictogrammers](https://pictogrammers.com), Apache-2.0) and the official
 * X logo, on the same 24px grid as everything above them.
 */

/** Filled (solid) heroicon. */
function Solid({ children, ...props }: SvgIconProps) {
  return (
    <SvgIcon viewBox="0 0 24 24" {...props}>
      {children}
    </SvgIcon>
  );
}

/** Stroked heroicon: the path carries the 1.5px outline. */
function Stroke({ children, ...rest }: SvgIconProps) {
  return (
    <SvgIcon viewBox="0 0 24 24" {...rest}>
      {children}
    </SvgIcon>
  );
}

